//! Twelve office concepts. Each differs in value structure and materials, not only hue.

#[derive(Clone, Copy, Debug, Hash, PartialEq, Eq)]
pub(super) enum Floor {
    Herringbone,
    Tiles,
    Grid,
    Carpet,
    Concrete,
    Checker,
    Planks,
    Tatami,
}

#[derive(Clone, Copy, Debug, Hash, PartialEq, Eq)]
pub(super) enum Wall {
    Plaster,
    Glass,
    Panels,
    Brick,
    Stripes,
    Logs,
    Shoji,
    Metal,
}

#[derive(Clone, Copy, Debug, Hash, PartialEq, Eq)]
pub(super) enum View {
    City,
    Garden,
    NightCity,
    Space,
    Snow,
    Sea,
    Bamboo,
}

#[derive(Clone, Copy, Debug, Hash, PartialEq, Eq)]
pub(super) enum DeskStyle {
    Wood,
    White,
    Metal,
    Low,
}

/// Large standing pieces that give a room its focal point.
#[derive(Clone, Copy, Debug, Hash, PartialEq, Eq)]
pub(super) enum Feature {
    Easel,
    Bookcase,
    Planter,
    PottingBench,
    ServerRack,
    Telescope,
    Globe,
    Workbench,
    Printer3d,
    EspressoBar,
    PastryCase,
    Arcade,
    Vending,
    HydroPod,
    Console,
    Fireplace,
    WoodPile,
    SurfRack,
    DeckChair,
    Bonsai,
    StoneLantern,
    Gumball,
}

#[derive(Clone, Copy, Debug, Hash, PartialEq, Eq)]
pub(super) enum Decor {
    Pinboard,
    Frame,
    HangingPlants,
    Shelf,
    MonitorWall,
    StarChart,
    Pegboard,
    Poster,
    Chalkboard,
    Bunting,
    Neon,
    Porthole,
    Skis,
    Lifebuoy,
    Scroll,
}

#[derive(Clone, Copy, Debug, Hash, PartialEq, Eq)]
pub(super) enum Clutter {
    FloorLamp,
    Crates,
    WateringCan,
    SmallPot,
    Bin,
    BookPile,
    Stool,
    LavaLamp,
    BeanBag,
    Cushion,
    PaperLantern,
}

#[derive(Clone, Copy, Debug, Hash, PartialEq, Eq)]
pub(super) enum Plant {
    Monstera,
    Fern,
    Palm,
    Snake,
    Cactus,
    Fir,
    Bamboo,
}

