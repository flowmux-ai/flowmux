pub(super) const LAYOUTS: usize = 4;
pub(super) const DESIGNS: usize = THEMES.len() * LAYOUTS;

pub(super) fn theme(design: usize) -> &'static Theme {
    &THEMES[design % DESIGNS / LAYOUTS]
}

pub(super) fn design_name(design: usize) -> String {
    let theme = theme(design);
    format!("{} / {}", theme.name, theme.layouts[design % LAYOUTS])
}
